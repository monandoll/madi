/** 이 영상에 맞는 포맷. 길이로 고른다 (세로로 찍은 원본이면 이미 숏폼 소재다). */
export function formatOf(video: { durationSec?: number | null; width?: number | null; height?: number | null }): Format {
  const sec = video.durationSec ?? 0;
  const vertical = !!video.width && !!video.height && video.height > video.width;
  if (vertical && sec <= 90) return 'reels';
  if (sec <= 90) return 'reels';
  return 'long';
}

/** 포맷 한 줄 요약 (프롬프트 맨 위에 붙는다). */
export function formatLine(f: Format): string {
  const s = FORMATS[f];
  return `${s.label} · ${s.aspect} · ${s.sec[0]}~${s.sec[1]}초 (최대 ${s.hardMaxSec}초)`;
}

/**
 * 에이전트 컨텍스트에 넣을 제작 지침 전체.
 * 롱폼 영상이면 챕터 지침까지, 짧은 영상이면 빼고 준다 (읽을 게 적을수록 잘 따른다).
 */
export function playbook(opts: { format: Format; hasAudio: boolean }): string {
  const out = ['# 제작 지침 (운동 · 재활 영상)', '', `이 영상의 기본 포맷: ${formatLine(opts.format)}`, ''];
  out.push(...CLIPPING, '');
  if (opts.format === 'long') out.push(...LONGFORM, '');
  if (opts.hasAudio) out.push(...SUBTITLES, '');
  else out.push('## 자막', '', '- 이 영상은 소리가 없다. 사용자가 문장을 주면 set_subtitle_text 로 넣는다. 없으면 자막 없이 만든다.', '');
  out.push(...CONVERSATION);
  return out.join('\n');
}
